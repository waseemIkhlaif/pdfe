#!/usr/bin/env node
// Builds the message catalogs of every app from the approved rows of the Phase 2 copy deck.
//
//   node scripts/generate.mjs           writes src/catalogs/{ar,en}.json and src/keys.ts
//   node scripts/generate.mjs --check   exits 1 if the committed files differ from what the deck gives
//
// The deck (docs/design/copy-decks/phase-02.md) is the single source of the words (FR-023, FR-033). Only rows whose Status is
// `approved` are emitted: nothing a reviewer has not signed off reaches a screen. Every key must exist in both languages, and
// every message must be valid ICU MessageFormat, or the build stops here, not on a user's screen.
import { existsSync, readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parse as parseIcu } from '@formatjs/icu-messageformat-parser';

const HERE = dirname(fileURLToPath(import.meta.url));
export const ROOT = resolve(HERE, '../../..');
export const DECK = join(ROOT, 'docs/design/copy-decks/phase-02.md');
export const OUT = resolve(HERE, '../src');

const KEY = /^[a-z][a-zA-Z0-9-]*(\.[a-zA-Z0-9][a-zA-Z0-9-]*)+$/;

/** The rows of the deck's table: { key, en, ar, status }. Lines that are not table rows are ignored. */
export function parseDeck(markdown) {
  const rows = [];
  for (const line of markdown.replace(/\r\n/g, '\n').split('\n')) {
    if (!line.startsWith('|')) continue;
    const cells = line
      .replace(/^\||\|$/g, '')
      .split('|')
      .map((c) => c.trim());
    if (cells.length < 8) continue;
    const [key, en, ar] = cells;
    if (key === 'Key' || /^-+$/.test(key)) continue;
    rows.push({ key, en, ar, status: cells[7] });
  }
  return rows;
}

/** Problems with the approved rows, as readable lines. Empty when the deck is fit to generate from. */
export function problems(rows) {
  const out = [];
  const seen = new Set();
  const keys = new Set(rows.map((r) => r.key));
  for (const r of rows) {
    if (!KEY.test(r.key))
      out.push(`${r.key}: not a valid key (dotted words, hyphens and camelCase allowed)`);
    if (seen.has(r.key)) out.push(`${r.key}: listed twice`);
    seen.add(r.key);
    for (const [lang, text] of [
      ['en', r.en],
      ['ar', r.ar],
    ]) {
      if (!text) {
        out.push(`${r.key}: no ${lang} text`);
        continue;
      }
      try {
        parseIcu(text);
      } catch (e) {
        out.push(`${r.key}: the ${lang} text is not valid ICU MessageFormat (${e.message})`);
      }
    }
    // A key cannot be both a message and the start of a group (`a.b` and `a.b.c`): the catalog is nested.
    for (const other of keys) {
      if (other.startsWith(`${r.key}.`))
        out.push(`${r.key}: is a message and also the prefix of ${other}`);
    }
  }
  return out;
}

/** Only the approved rows, sorted by key. */
export const approved = (rows) =>
  rows
    .filter((r) => r.status.toLowerCase() === 'approved')
    .sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));

/** { ui: { 'sign-in': 'Sign in' } } from the dotted keys. */
export function nest(rows, lang) {
  const root = {};
  for (const r of rows) {
    const path = r.key.split('.');
    let node = root;
    for (const p of path.slice(0, -1)) node = node[p] ??= {};
    node[path.at(-1)] = r[lang];
  }
  return root;
}

export function keysFile(rows) {
  const list = rows.map((r) => `  '${r.key}',`).join('\n');
  return `// Generated by scripts/generate.mjs from docs/design/copy-decks/phase-02.md (approved rows). Do not edit.
export const MESSAGE_KEYS = [
${list}
] as const;

export type MessageKey = (typeof MESSAGE_KEYS)[number];
`;
}

const json = (v) => `${JSON.stringify(v, null, 2)}\n`;

/** The three generated files as { path: content }, from the deck text. Throws with every problem when the deck is not fit. */
export function generateFiles(markdown) {
  const all = parseDeck(markdown);
  const rows = approved(all);
  const bad = problems(rows);
  if (bad.length > 0) throw new Error(`the copy deck cannot be used:\n  ${bad.join('\n  ')}`);
  if (rows.length === 0) throw new Error('the copy deck has no approved rows');
  return {
    'catalogs/en.json': json(nest(rows, 'en')),
    'catalogs/ar.json': json(nest(rows, 'ar')),
    'keys.ts': keysFile(rows),
  };
}

/** Every `t('some.key')` in the source files under `dirs`: [{ key, file, line }]. */
export function usedKeys(dirs, root = ROOT) {
  const found = [];
  const skip = new Set([
    'node_modules',
    'dist',
    '.next',
    '.turbo',
    'coverage',
    'test',
    '__snapshots__',
  ]);
  const walk = (d) => {
    if (!existsSync(d)) return;
    for (const name of readdirSync(d)) {
      if (skip.has(name)) continue;
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (/\.(ts|tsx)$/.test(name) && !name.endsWith('.d.ts')) {
        const lines = readFileSync(p, 'utf8').split('\n');
        lines.forEach((text, i) => {
          for (const m of text.matchAll(
            /\b(?:t|tr|translate)\(\s*(?:locale\s*,\s*)?['"]([a-z][a-zA-Z0-9-]*(?:\.[a-zA-Z0-9-]+)+)['"]/g,
          )) {
            found.push({ key: m[1], file: relative(root, p).replace(/\\/g, '/'), line: i + 1 });
          }
        });
      }
    }
  };
  for (const d of dirs) walk(resolve(root, d));
  return found;
}

/** The keys code uses that the catalog does not have: [{ key, file, line }]. */
export function missingKeys(used, known) {
  const set = new Set(known);
  return used.filter((u) => !set.has(u.key));
}

function main() {
  const check = process.argv.includes('--check');
  let files;
  try {
    files = generateFiles(readFileSync(DECK, 'utf8'));
  } catch (e) {
    console.error(`i18n: ${e.message}`);
    process.exit(1);
  }
  let stale = false;
  for (const [rel, content] of Object.entries(files)) {
    const target = join(OUT, rel);
    const have = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : null;
    if (check) {
      if (have !== content) {
        console.error(
          `i18n: ${relative(ROOT, target)} is out of date: run pnpm --filter @pdfe/i18n generate`,
        );
        stale = true;
      }
    } else if (have !== content) {
      writeFileSync(target, content, 'utf8');
    }
  }
  if (stale) process.exit(1);

  // Every key the code uses must exist (a missing key would show as the raw key on a screen).
  const known = Object.keys(files).includes('keys.ts')
    ? [...files['keys.ts'].matchAll(/^ {2}'([^']+)',$/gm)].map((m) => m[1])
    : [];
  const missing = missingKeys(
    usedKeys(['apps', 'packages/ui-web/src', 'packages/ui-native/src', 'packages/auth-web/src']),
    known,
  );
  if (missing.length > 0) {
    for (const m of missing)
      console.error(`i18n: ${m.file}:${m.line} uses ${m.key}, which is not in the catalog`);
    process.exit(1);
  }
  console.log(`i18n: ${known.length} messages in ar and en${check ? ' (up to date)' : ''}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
