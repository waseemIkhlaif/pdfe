// Style Dictionary v4 configuration (DTCG). Contract: specs/000-ux-design-track/contracts/token-pipeline.md
// Outputs: web CSS custom properties, React Native theme, flat resolved JSON. Deterministic: no timestamps.
import StyleDictionary from 'style-dictionary';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const GROUPS = ['color', 'typography', 'spacing', 'radius', 'elevation', 'motion', 'breakpoint'];
const HEADER = ['Do not edit. Generated by packages/design-tokens/sd.build.mjs from tokens/*.json.'];

const val = (t) => t.$value ?? t.value;
const camel = (s) => s.replace(/[-_ ]+([a-zA-Z0-9])/g, (_, c) => c.toUpperCase());

function sortKeys(o) {
  if (Array.isArray(o) || o === null || typeof o !== 'object') return o;
  return Object.fromEntries(Object.keys(o).sort().map((k) => [k, sortKeys(o[k])]));
}

function toNative(t) {
  const native = (t.$extensions ?? t.extensions)?.pdfe?.native;
  if (native) return native;
  const v = val(t);
  if (typeof v === 'string') {
    const m = v.match(/^(-?\d+(?:\.\d+)?)(px|ms)$/);
    if (m) return Number(m[1]);
  }
  return v;
}

StyleDictionary.registerTransformGroup({ name: 'pdfe/css', transforms: ['attribute/cti', 'name/kebab', 'color/css'] });
StyleDictionary.registerTransformGroup({ name: 'pdfe/data', transforms: ['attribute/cti'] });

StyleDictionary.registerFormat({
  name: 'pdfe/native-ts',
  format: ({ dictionary }) => {
    const tree = {};
    for (const t of dictionary.allTokens) {
      let node = tree;
      t.path.forEach((seg, i) => {
        const key = camel(seg);
        if (i === t.path.length - 1) node[key] = toNative(t);
        else node = node[key] ??= {};
      });
    }
    return `// ${HEADER[0]}\nexport const theme = ${JSON.stringify(sortKeys(tree), null, 2)} as const;\n`;
  },
});

StyleDictionary.registerFormat({
  name: 'pdfe/resolved-json',
  format: ({ dictionary }) => {
    const flat = {};
    for (const t of dictionary.allTokens) flat[t.path.join('.')] = val(t);
    return JSON.stringify(sortKeys(flat), null, 2) + '\n';
  },
});

export function makeConfig(outDir) {
  const base = outDir.replaceAll('\\', '/').replace(/\/?$/, '/');
  return {
    usesDtcg: true,
    log: { warnings: 'warn', verbosity: 'silent' },
    source: GROUPS.map((g) => path.join(root, 'tokens', `${g}.json`).replaceAll('\\', '/')),
    hooks: { fileHeaders: { pdfe: () => HEADER } },
    platforms: {
      web: {
        transformGroup: 'pdfe/css',
        prefix: 'pdfe',
        buildPath: `${base}web/`,
        files: [{ destination: 'tokens.css', format: 'css/variables', options: { selector: ':root', outputReferences: false, fileHeader: 'pdfe' } }],
      },
      native: {
        transformGroup: 'pdfe/data',
        buildPath: `${base}native/`,
        files: [{ destination: 'theme.ts', format: 'pdfe/native-ts' }],
      },
      resolved: {
        transformGroup: 'pdfe/data',
        buildPath: base,
        files: [{ destination: 'tokens.resolved.json', format: 'pdfe/resolved-json' }],
      },
    },
  };
}

export { StyleDictionary };
