// Builds the data the prototype needs from the repository's own files:
//  - docs/design/prototype/inventory.js  from docs/design/screen-inventory.md
//  - docs/design/prototype/tokens.css    from packages/design-tokens/dist/web/tokens.css (run `pnpm build` there first)
// Deterministic: no timestamps.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const proto = path.join(root, 'docs', 'design', 'prototype');

export function readInventory() {
  const lines = fs.readFileSync(path.join(root, 'docs', 'design', 'screen-inventory.md'), 'utf8').split(/\r?\n/);
  const rows = [];
  for (const l of lines) {
    if (!l.startsWith('|')) continue;
    const c = l.split('|').slice(1, -1).map((x) => x.trim());
    if (c.length !== 14 || !/^[A-Z]{3}-\d{3}$/.test(c[0])) continue;
    rows.push({
      id: c[0], ifc: c[1], name: c[2], phase: parseInt(c[3], 10), journeys: c[4] === '—' ? '' : c[4],
      sizes: c[6].split(','), money: c[7], skeleton: c[8],
    });
  }
  return rows;
}

export function main() {
  const inv = readInventory();
  if (inv.length === 0) throw new Error('no inventory rows found');
  const body = `/* Generated by scripts/design/render/prepare.mjs from docs/design/screen-inventory.md. Do not edit. */\nwindow.PDFE = window.PDFE || {};\nwindow.PDFE.inventory = ${JSON.stringify(inv, null, 1)};\n`;
  fs.writeFileSync(path.join(proto, 'inventory.js'), body, 'utf8');
  const tokens = path.join(root, 'packages', 'design-tokens', 'dist', 'web', 'tokens.css');
  if (!fs.existsSync(tokens)) throw new Error('tokens.css missing: run `pnpm --dir packages/design-tokens build` first');
  fs.copyFileSync(tokens, path.join(proto, 'tokens.css'));
  console.log(`prototype data written (${inv.length} screens)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
